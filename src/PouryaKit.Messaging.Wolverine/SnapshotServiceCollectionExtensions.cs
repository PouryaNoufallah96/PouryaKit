using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Microsoft.Extensions.Hosting;
using PouryaKit.Domain;

namespace PouryaKit.Messaging.Wolverine;

public static class SnapshotServiceCollectionExtensions
{
    extension(IServiceCollection services)
    {
        /// <summary>
        /// Declares that <paramref name="module"/>, the Module's definition type, publishes the Snapshot
        /// <typeparamref name="TSnapshot"/> of every <typeparamref name="TAggregate"/> under
        /// <paramref name="wireName"/>, built by <typeparamref name="TMapper"/>. Whenever an Operation of
        /// <paramref name="module"/> changes such an aggregate, anything it holds included, its Unit of Work builds one
        /// Snapshot of it from its final state, or a Tombstone when the Operation removed it, carrying the version it
        /// commits, and writes it to the Outbox in the same commit, once for each subscription; a rolled-back Operation
        /// publishes none. The mapper only reads, as a step of the Unit of Work that only reads: an Operation whose mapper
        /// sends a command, writes through a repository or the Unit of Work's connection, changes anything the Unit of
        /// Work saves, complex collections included, or changes pending Domain Events, fails with nothing committed.
        /// Changes restored before the read boundary ends are not detected. Other Modules subscribe to it with <c>Subscribe</c>, as to an Integration
        /// Event, and their handler runs only for a version newer than every one it applied of that aggregate, so a late,
        /// duplicated or concurrent older Snapshot is never applied. The wire name is stable: keep it when the type is
        /// renamed. Three rules are checked when an Operation that changes such an aggregate commits, not at startup, and
        /// fail it: <typeparamref name="TAggregate"/> covers one mapped aggregate hierarchy only, never two separately
        /// mapped aggregates such as two roots sharing a base type; the declaration names its Module in a Host of Modules,
        /// and none in an application without them; and the aggregate's key is set by the application, not generated by
        /// the database. Once an aggregate is deleted outright its key is never used again, since every receiver has
        /// applied its Tombstone's version and would turn away a new aggregate's lower ones; the Kit's Guid version 7 keys
        /// never are, and a soft-deleted aggregate keeps its key and its version. Throws here, at startup, as
        /// <c>Publish</c> does, and when the type is already published as an Integration Event or as another
        /// declaration's Snapshot.
        /// </summary>
        public IServiceCollection PublishSnapshot<TAggregate, TSnapshot, TMapper>(string wireName, Type? module = null)
            where TAggregate : class, IAggregateRoot
            where TSnapshot : class
            where TMapper : class, ISnapshotMapper<TAggregate, TSnapshot>
        {
            ArgumentNullException.ThrowIfNull(services);
            Subscriptions
                .In(services)
                .PublishSnapshot(new SnapshotPublication(typeof(TAggregate), typeof(TSnapshot), typeof(TMapper)), wireName, module);
            services.TryAddScoped<TMapper>();
            services.TryAddEnumerable(ServiceDescriptor.Singleton<IHostedService, StartupCheck>());
            return services;
        }
    }
}
