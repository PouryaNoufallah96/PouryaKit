using System.Collections.Concurrent;
using System.Collections.Frozen;
using System.Globalization;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata;
using PouryaKit.Domain;
using PouryaKit.Persistence.EFCore;

namespace PouryaKit.Messaging.Wolverine.EFCore;

// Step 4 of the Unit of Work's commit sequence: one Snapshot of each aggregate the prepare step advanced, under each
// contract declared for it, a Tombstone when the Operation removed it, kept marked deleted or deleted outright, each
// with the aggregate's key and the version being committed. Built from the prepared state, which nothing may change
// afterwards (ADR 0003), so the mappers' run is checked against it: anything they changed, or a Domain Event they
// raised, fails the Operation, complex collection contents included. Changes restored before comparison are not seen. One declaration
// covers the aggregates of one mapped hierarchy only, whose keys its identities and versions can tell apart. Nothing in
// an aggregate's mapped graph may have a value the database generates when it is saved, which a Snapshot built before the
// save would publish stale.
internal static class SnapshotStep
{
    // Read once per DbContext type, whose model EF builds once and never changes; the declarations are the Host's, so
    // the key-space check itself still runs at each commit, over this.
    private static readonly ConcurrentDictionary<Type, MappedAggregates> Models = new();

    public static List<(object Snapshot, string AggregateId, long Version)> Build(
        DbContext dbContext,
        IReadOnlyList<EntityEntry> changedAggregates,
        ISnapshotMappers mappers
    )
    {
        var declared = changedAggregates.Where(entry => mappers.Declares(entry.Entity.GetType())).ToList();
        if (declared.Count == 0)
        {
            return [];
        }

        var mapped = Models.GetOrAdd(dbContext.GetType(), static (_, model) => MappedAggregates.Of(model), dbContext.Model);
        mappers.CheckKeySpaces(mapped.Roots);

        using var prepared = TrackedState.Capture(dbContext);
        List<(object, string, long)> built = [];
        foreach (var entry in declared)
        {
            if (mapped.Generated.GetValueOrDefault(entry.Metadata.ClrType) is { } generated)
            {
                var part = $"{generated.DeclaringType.ClrType.Name}.{generated.Name}";
                throw new InvalidOperationException(
                    $"A Snapshot of {entry.Metadata.ClrType.Name} is declared, but {part} is generated by the database when it is saved, after the Snapshot is built, so the Snapshot would not carry the value committed. Have the application set {part}: map it with no default value SQL, computed column or generated value."
                );
            }

            var removed = entry.State == EntityState.Deleted || entry.Entity is ISoftDeletable { IsDeleted: true };
            var aggregateId = AggregateId(entry);
            var version = (long)entry.Property(nameof(IAggregateRoot.Version)).CurrentValue!;
            built.AddRange(mappers.Map(entry.Entity, removed).Select(snapshot => (snapshot, aggregateId, version)));
        }

        prepared.ThrowIfChanged("A Snapshot mapper");
        return built;
    }

    // Encode provider values without losing precision. One part keeps its existing scalar format; several parts
    // prefix each with its invariant length, so no two keys read alike.
    private static string AggregateId(EntityEntry entry)
    {
        List<string> parts =
        [
            .. entry.Metadata.FindPrimaryKey()!.Properties.Select(property =>
            {
                var key = entry.Property(property.Name);
                return key.IsTemporary
                    ? throw new InvalidOperationException(
                        $"A Snapshot of {entry.Metadata.ClrType.Name} is declared, but its key is generated by the database when it is saved, after the Snapshot is built. Give {entry.Metadata.ClrType.Name} a key the application sets, such as a Guid version 7."
                    )
                    : KeyPart(
                        property,
                        property.GetTypeMapping().Converter is { } converter
                            ? converter.ConvertToProvider(key.CurrentValue)
                            : key.CurrentValue
                    );
            }),
        ];
        return parts.Count == 1 ? parts[0] : string.Concat(parts.Select(part => $"{part.Length.ToString(CultureInfo.InvariantCulture)}:{part}"));
    }

    private static string KeyPart(IProperty property, object? value) =>
        value switch
        {
            Guid id => id.ToString(),
            int id => id.ToString(CultureInfo.InvariantCulture),
            long id => id.ToString(CultureInfo.InvariantCulture),
            string id => id,
            byte[] id => Convert.ToHexString(id),
            DateTime id => TimestampKey(property, id),
            _ => throw new InvalidOperationException(
                $"The Snapshot key {property.DeclaringType.ClrType.Name}.{property.Name} has unsupported provider type {value?.GetType().FullName ?? "null"}. Use a non-null Guid, int, long, string, byte[] or a losslessly mapped DateTime."
            ),
        };

    private static string TimestampKey(IProperty property, DateTime value)
    {
        var mapping = property.GetRelationalTypeMapping();
        var precision = mapping.Precision ?? 6;
        var storeType = mapping.StoreTypeNameBase;
        var supportedTimestamp = storeType.Equals("timestamp with time zone", StringComparison.OrdinalIgnoreCase)
            || storeType.Equals("timestamp without time zone", StringComparison.OrdinalIgnoreCase)
            || storeType.Equals("timestamptz", StringComparison.OrdinalIgnoreCase)
            || storeType.Equals("timestamp", StringComparison.OrdinalIgnoreCase);
        if (
            !supportedTimestamp
            || precision is < 0 or > 6
            || value.Ticks % (long)Math.Pow(10, 7 - precision) != 0
        )
        {
            throw new InvalidOperationException(
                $"The Snapshot key {property.DeclaringType.ClrType.Name}.{property.Name} cannot round-trip its DateTime through {mapping.StoreType}. Use a PostgreSQL timestamp with precision at most 6 and a value aligned to that precision, or convert the key to a lossless supported provider type."
            );
        }

        // PostgreSQL's timestamp without time zone reloads with Unspecified Kind; the ticks still identify the key.
        return value.Ticks.ToString(CultureInfo.InvariantCulture);
    }

    // Every aggregate type the model maps, with the root of its hierarchy, in the model's order, which the key-space
    // refusal lists them in; and the first property in each one's mapped graph whose value the database generates.
    private sealed record MappedAggregates(IReadOnlyDictionary<Type, Type> Roots, FrozenDictionary<Type, IProperty> Generated)
    {
        public static MappedAggregates Of(IModel model)
        {
            List<IEntityType> aggregates =
            [
                .. model
                    .GetEntityTypes()
                    .Where(type => !type.IsOwned() && type.ClrType.IsAssignableTo(typeof(IAggregateRoot)))
                    .DistinctBy(type => type.ClrType),
            ];
            return new(
                aggregates.ToDictionary(type => type.ClrType, type => type.GetRootType().ClrType),
                aggregates
                    .Select(type => (type.ClrType, Generated: GeneratedIn(type)))
                    .Where(aggregate => aggregate.Generated is not null)
                    .ToFrozenDictionary(aggregate => aggregate.ClrType, aggregate => aggregate.Generated!)
            );
        }

        // The graph the prepare step attributes changes to the aggregate by: the aggregate, every type it owns and every
        // child it holds through a navigation, their derived types included, down to another aggregate. A key is left
        // out: the Kit's are set by the application, and the aggregate's own is refused when it is still temporary.
        private static IProperty? GeneratedIn(IEntityType aggregate)
        {
            HashSet<IEntityType> seen = [];
            Stack<IEntityType> pending = new([aggregate]);
            while (pending.TryPop(out var type))
            {
                if (!seen.Add(type))
                {
                    continue;
                }

                if (type.GetFlattenedProperties().FirstOrDefault(IsGenerated) is { } generated)
                {
                    return generated;
                }

                foreach (
                    var part in type.GetReferencingForeignKeys()
                        .Where(foreignKey => foreignKey.PrincipalToDependent is not null)
                        .SelectMany(foreignKey => foreignKey.DeclaringEntityType.GetDerivedTypesInclusive())
                        .Where(part => !part.ClrType.IsAssignableTo(typeof(IAggregateRoot)))
                )
                {
                    pending.Push(part);
                }
            }

            return null;
        }

        private static bool IsGenerated(IProperty property) =>
            !property.IsKey()
            && (
                property.ValueGenerated != ValueGenerated.Never
                || property.GetDefaultValueSql() is not null
                || property.GetComputedColumnSql() is not null
            );
    }
}
